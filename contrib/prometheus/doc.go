// Package prometheus — реализация taskq.Meter для Prometheus
// (github.com/prometheus/client_golang).
//
// Метрики создаются лениво при первом обращении Counter/Histogram/Gauge
// и регистрируются в prometheus.Registerer, переданном в NewMeter.
// Повторные обращения по тому же имени возвращают уже зарегистрированный
// вектор, поэтому ядро может звать Counter("taskq.submitted") на каждую
// задачу без повторной регистрации.
//
// Соответствие модели taskq модели Prometheus:
//
//   - имя метрики санитизируется под правила Prometheus: точки и прочие
//     недопустимые символы заменяются на "_" ("taskq.submitted" →
//     "taskq_submitted"), опциональный namespace становится префиксом;
//   - MetricAttr становятся лейблами. Набор лейблов фиксирован на уровне
//     Meter (по умолчанию "task" — единственный атрибут, который эмитит ядро)
//     и задается опцией WithLabels; атрибуты с другими ключами игнорируются,
//     отсутствующий атрибут дает пустое значение лейбла;
//   - WithMetricDescription становится Help метрики, WithMetricUnit
//     дописывается в Help (юниты в Prometheus принято вшивать в имя);
//   - Histogram.Record переводит time.Duration в секунды — гистограммы
//     наблюдаются в секундах (Observe(d.Seconds())).
//
// При неустранимой ошибке регистрации (имя занято метрикой другого типа,
// невалидные лейблы) методы создания метрик паникуют, как promauto:
// это ошибка конфигурации, а не исполнения задачи.
